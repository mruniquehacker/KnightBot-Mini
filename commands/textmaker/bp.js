/**
 * BLACKPINK Text Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'blackpink',
  aliases: ['bp', 'bplogo'],
  category: 'textmaker',
  description: 'Create a BLACKPINK style logo',
  usage: '.blackpink <text>',

  async execute(sock, msg, args) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;

      if (!text) {
        return await sock.sendMessage(chatId, {
          text: 'Please provide text.\nExample: .blackpink KnightBot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/online-blackpink-style-logo-maker-effect-711.html',
        text
      );

      if (!result || !result.image) {
        throw new Error('No image URL received.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `🖤💗 BLACKPINK Logo\n\n📝 Text: ${text}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in blackpink command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
