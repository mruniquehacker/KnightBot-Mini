/**
 * PornHub Style Logo
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'pornhub',
  aliases: ['phlogo', 'ph'],
  category: 'textmaker',
  description: 'Create a PornHub-style logo',
  usage: '.pornhub <left text>|<right text>',

  async execute(sock, msg, args) {
    try {
      const chatId = msg.key.remoteJid;
      const input = args.join(' ');

      if (!input.includes('|')) {
        return await sock.sendMessage(chatId, {
          text:
`Please provide two texts separated by "|"

Example:
.pornhub Knight|Bot`
        }, { quoted: msg });
      }

      const [left, right] = input.split('|').map(v => v.trim());

      if (!left || !right) {
        return await sock.sendMessage(chatId, {
          text: 'Both texts are required.\n\nExample:\n.pornhub Knight|Bot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/create-pornhub-style-logos-online-free-549.html',
        [left, right]
      );

      if (!result || !result.image) {
        throw new Error('No image URL received.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `🟧⬛ *PornHub Style Logo*\n\n📝 ${left} | ${right}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in pornhub command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
