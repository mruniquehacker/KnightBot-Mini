/**
 * Neon Glitch Text Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'neonglitch',
  aliases: ['glitch', 'neon'],
  category: 'textmaker',
  description: 'Create a neon glitch text effect',
  usage: '.neonglitch <text>',

  async execute(sock, msg, args) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;

      if (!text) {
        return await sock.sendMessage(chatId, {
          text: 'Please provide text.\nExample: .neonglitch KnightBot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/create-impressive-neon-glitch-text-effects-online-768.html',
        text
      );

      if (!result || !result.image) {
        throw new Error('No image URL received from Ephoto360.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `⚡ *Neon Glitch Effect*\n\n📝 Text: ${text}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in neonglitch command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
