/**
 * Wet Glass Text Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'wetglass',
  aliases: ['glass', 'rainglass'],
  category: 'textmaker',
  description: 'Create a wet glass text effect',
  usage: '.wetglass <text>',

  async execute(sock, msg, args) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;

      if (!text) {
        return await sock.sendMessage(chatId, {
          text: 'Please provide text.\nExample: .wetglass KnightBot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/write-text-on-wet-glass-online-589.html',
        text
      );

      if (!result || !result.image) {
        throw new Error('No image URL received from Ephoto360.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `💧 *Wet Glass Effect*\n\n📝 Text: ${text}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in wetglass command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
