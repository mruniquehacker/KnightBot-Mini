/**
 * Typography Art Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'typography',
  aliases: ['typo', 'layers'],
  category: 'textmaker',
  description: 'Create a multi-layer typography art effect',
  usage: '.typography <text>',

  async execute(sock, msg, args) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;

      if (!text) {
        return await sock.sendMessage(chatId, {
          text: 'Please provide text.\nExample: .typography KnightBot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/create-online-typography-art-effects-with-multiple-layers-811.html',
        text
      );

      if (!result || !result.image) {
        throw new Error('No image URL received from Ephoto360.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `🎨 *Typography Art*\n\n📝 Text: ${text}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in typography command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
