/**
 * Graffiti Text Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'graffiti',
  aliases: ['graff', 'spray'],
  category: 'textmaker',
  description: 'Create a graffiti text effect',
  usage: '.graffiti <text>',

  async execute(sock, msg, args) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;

      if (!text) {
        return await sock.sendMessage(chatId, {
          text: 'Please provide text.\nExample: .graffiti KnightBot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/graffiti-text-text-effect-online-178.html',
        text
      );

      if (!result || !result.image) {
        throw new Error('No image URL received from Ephoto360.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `🎨 *Graffiti Text*\n\n📝 Text: ${text}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in graffiti command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
