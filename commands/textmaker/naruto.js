/**
 * Naruto Shippuden Logo
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'naruto',
  aliases: ['narutologo', 'shippuden'],
  category: 'textmaker',
  description: 'Create a Naruto Shippuden style logo',
  usage: '.naruto <text>',

  async execute(sock, msg, args) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;

      if (!text) {
        return await sock.sendMessage(chatId, {
          text: 'Please provide text.\nExample: .naruto KnightBot'
        }, { quoted: msg });
      }

      const result = await mumaker.ephoto(
        'https://en.ephoto360.com/naruto-shippuden-logo-style-text-effect-online-808.html',
        text
      );

      if (!result || !result.image) {
        throw new Error('No image URL received from Ephoto360.');
      }

      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `🍥 *Naruto Shippuden Logo*\n\n📝 Text: ${text}\n\n> Generated by ${config.botName}`
      }, { quoted: msg });

    } catch (error) {
      console.error('Error in naruto command:', error);

      await sock.sendMessage(msg.key.remoteJid, {
        text: `❌ Error: ${error.message}`
      }, { quoted: msg });
    }
  }
};
